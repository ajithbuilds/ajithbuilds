"""Build offline previews, a static edition, and poster frames from README.md.

Usage: python3 scripts/build_preview.py
Dependencies: Pillow, mistune, beautifulsoup4. Does not fetch network resources.
"""
from pathlib import Path
from html import escape
import hashlib,json,re
import mistune
from bs4 import BeautifulSoup
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parent.parent
STATIC=ROOT/'assets/static'
COUNTER='https://komarev.com/ghpvc/?username=ajithkumarren&color=1565C0&style=flat-square&label=Profile+Views'

def write_text_atomic(path,content):
    temporary=path.with_name('.'+path.name+'.tmp')
    temporary.write_text(content)
    temporary.replace(path)

def source_paths(md):
    return sorted(set(re.findall(r'(?:src="|\]\()(assets/[^"\)]+\.gif)',md)))

def make_posters(md):
    mapping={}
    cache_path=STATIC/'poster-digests.json'
    previous=json.loads(cache_path.read_text()) if cache_path.exists() else {}
    current={}
    for rel in source_paths(md):
        src=ROOT/rel
        target=STATIC/Path(rel).relative_to('assets').with_suffix('.png')
        target.parent.mkdir(parents=True,exist_ok=True)
        full=src.with_suffix('.png')
        source_digest=hashlib.sha256(src.read_bytes()+(full.read_bytes() if 'architecture' in src.stem and full.exists() else b'')+b'poster-v1').hexdigest()
        if not target.exists() or previous.get(rel,{}).get('source')!=source_digest or previous.get(rel,{}).get('poster')!=hashlib.sha256(target.read_bytes()).hexdigest():
            with Image.open(src) as im:
                # Full diagrams use the static all-components render, rather than one active stage.
                full=src.with_suffix('.png')
                if 'architecture' in src.stem and full.exists():poster=Image.open(full).convert('RGB')
                else:
                    k=75 if src.name.startswith('hero-') else (12 if src.name=='coding.gif' else 0)
                    im.seek(min(k,im.n_frames-1));poster=im.convert('RGB')
                if src.name=='headings.gif':
                    poster=Image.new('RGB',(960,68),'black');d=ImageDraw.Draw(poster)
                    font=ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial.ttf',23)
                    d.text((480,34),'Platform Engineering  ·  SRE  ·  AIOps & MLOps',font=font,fill='#a6c8ff',anchor='mm')
                temporary=target.with_suffix(".tmp.png")
                poster.save(temporary,optimize=True)
                temporary.replace(target)
        mapping[rel]=target.relative_to(ROOT).as_posix()
        current[rel]={'source':source_digest,'poster':hashlib.sha256(target.read_bytes()).hexdigest()}
    write_text_atomic(cache_path,json.dumps(current,indent=2)+'\n')
    return mapping

def static_markdown(md,mapping):
    # Replace entire motion-aware pictures; remaining prose and links stay identical.
    def replace(match):
        content=match.group(0)
        image=re.search(r'<img\b[^>]*>',content)
        if not image:return content
        if not any(src in content for src in mapping):return content
        result=image.group(0)
        for src,dst in mapping.items():result=result.replace('src="'+src+'"','src="'+dst+'"')
        return result
    md=re.sub(r'<picture>.*?</picture>',replace,md,flags=re.S)
    for src,dst in mapping.items():md=md.replace('src="'+src+'"','src="'+dst+'"')
    return '<!-- Generated by scripts/build_preview.py; edit README.md instead. -->\n\n'+md

def render(md):
    # Never fetch the remote counter while locally reviewing the profile.
    md=md.replace('![Profile views]('+COUNTER+')','<small class="counter-note">Profile views · original counter retained</small>')
    html=mistune.create_markdown(escape=False,plugins=['table','strikethrough'])(md)
    soup=BeautifulSoup(html,'html.parser')
    for image in soup.find_all('img'):
        if image.get('src','').startswith('http'):raise ValueError('Unexpected remote preview image')
        image['decoding']='async'
    # A native table preserves left/right alignment in GitHub's README renderer.
    # The local preview replaces it with the responsive glass toolbar.
    header_table=soup.find('table',class_='profile-header')
    if header_table:
        holder=soup.new_tag('div')
        contact=header_table.find(class_='banner-contact').extract()
        navigation=header_table.find(class_='profile-nav').extract()
        contact.name='p'
        navigation.name='p'
        header_table.replace_with(holder)
        holder.append(contact)
        holder.append(navigation)
    for table in soup.find_all('table'):
        wrap=soup.new_tag('div',attrs={'class':'table-scroll','tabindex':'0','aria-label':'Scrollable table'})
        table.wrap(wrap)
    # Render the README jump links as the banner toolbar at their inline position.
    navigation=soup.find('p',class_='profile-nav')
    if navigation:
        toolbar=BeautifulSoup('<header class="preview-toolbar"><nav aria-label="Profile navigation"><a href="#work">WORK</a><a href="#experience">EXPERIENCE</a><a href="#tech-stack">STACK</a></nav></header>','html.parser')
        navigation.replace_with(toolbar.header)
    # Keep contact links and navigation together on one scrollable line.
    contact=soup.find('p',class_='banner-contact')
    toolbar=soup.find('header',class_='preview-toolbar')
    if contact and toolbar:
        topbar=soup.new_tag('div',attrs={'class':'profile-topbar','tabindex':'0','role':'group','aria-label':'Contact links and profile navigation'})
        contact.insert_before(topbar)
        topbar.append(contact.extract())
        topbar.append(toolbar.extract())
    # Static-edition links open a rendered local view instead of raw Markdown.
    for link in soup.find_all('a',href=True):
        if link['href']=='PROFILE-STATIC.md':link['href']='preview-static.html'
        elif link['href']=='README.md':link['href']='preview.html'
    return str(soup)

def page(content):
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>AJITH KUMAR BALASUBRAMANIAN | Platform Engineer &amp; SRE</title><link rel="stylesheet" href="assets/preview.css"></head>
<body>
<main id="top"><h1 class="sr-only">AJITH KUMAR BALASUBRAMANIAN — Platform Engineering &amp; SRE</h1>{content}</main></body></html>'''

def main():
    md=(ROOT/'README.md').read_text()
    mapping=make_posters(md)
    write_text_atomic(ROOT/'assets/animation-manifest.json',json.dumps(mapping,indent=2)+'\n')
    static=static_markdown(md,mapping)
    write_text_atomic(ROOT/'PROFILE-STATIC.md',static)
    write_text_atomic(ROOT/'preview.html',page(render(md)))
    write_text_atomic(ROOT/'preview-static.html',page(render(static)))
    paths={i.get('src') for i in BeautifulSoup(render(md),'html.parser').find_all('img')} | set(mapping.values()) | {'assets/preview.css'}
    asset_hashes={rel:hashlib.sha256((ROOT/rel).read_bytes()).hexdigest() for rel in sorted(paths)}
    write_text_atomic(ROOT/'docs/preview-build.json',json.dumps({'readme_sha256':hashlib.sha256(md.encode()).hexdigest(),'asset_sha256':asset_hashes,'animated_assets':len(mapping),'remote_counter_loaded':False},indent=2)+'\n')
    print(f'Built two offline previews and static edition; {len(mapping)} poster alternatives.')
if __name__=='__main__':main()
